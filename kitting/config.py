"""共通の定数（寸法はすべてmm）。

トレイ（カートの棚板）は 1200 x 600 mm。これを 75 mm 角の「ブロック」に分け、
横 16 x 縦 8 = 128 ブロックの格子として扱う。ビンの外形はブロックの整数倍にそろえる。
"""

BLOCK_MM = 75                      # 1ブロックの一辺 [mm]
TRAY_W, TRAY_H = 16, 8             # トレイの格子（横, 縦）[ブロック]
TRAY_MM = (TRAY_W * BLOCK_MM, TRAY_H * BLOCK_MM)   # (1200, 600)
WALL_MM = 10                       # ビンの外形と内寸の差（壁の厚み＋すき間）[mm]

# ビン寸法の候補（ブロック単位、横 >= 縦）。第4章ではこの中から K 種類を選ぶ。
CANDIDATE_BINS = [
    (w, h)
    for w in (1, 2, 3, 4, 6, 8)
    for h in (1, 2, 3, 4)
    if h <= w
]

# 論文（2008）で使った標準ビン4種に相当する寸法（ブロック単位）
THESIS_BINS = [(1, 1), (2, 2), (4, 2), (4, 4)]

# 乱数の種（本の数値はすべてこの種で再現する）
DEFAULT_SEED = 2008
